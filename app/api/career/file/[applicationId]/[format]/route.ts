import type { NextRequest } from 'next/server';
import { requireUser } from '@/lib/auth/session';
import { getApplicationFiles, getCareerRow, signedCareerUrl } from '@/lib/career/repository';
import { resumeFileName } from '@/lib/career/send-plan';
import { isUuid } from '@/lib/validate/id';

// GET /api/career/file/<applicationId>/pdf|docx → the tailored resume.
//
// Owner-checked: the session decides who is asking, and the application is
// read through it, so row-level security returns nothing for anyone else's.
// The answer is a redirect to a one-minute signed Storage link that downloads
// as "<Name> - Resume.pdf". Anyone who isn't the owner gets the same 404 as a
// file that doesn't exist, so the route never confirms an id.

const SIGNED_SECONDS = 60;
const NO_STORE = { 'cache-control': 'no-store' };

const notFound = () => new Response('Not found', { status: 404, headers: NO_STORE });

// Typed by hand rather than RouteContext<…>: that type is generated by next dev/build, so tsc alone wouldn't know this route.
export async function GET(_request: NextRequest, ctx: { params: Promise<{ applicationId: string; format: string }> }) {
  const { applicationId, format } = await ctx.params;
  if (!isUuid(applicationId) || (format !== 'pdf' && format !== 'docx')) return notFound();
  const session = await requireUser();
  if (!session) return notFound();
  try {
    const [files, row] = await Promise.all([
      getApplicationFiles(session.userId, applicationId, session.supabase),
      getCareerRow(session.userId, session.supabase),
    ]);
    const path = format === 'pdf' ? files?.pdfPath : files?.docxPath;
    if (!path) return notFound();
    const url = await signedCareerUrl(session.userId, path, { download: resumeFileName(row?.profile?.contact.name ?? '', format), seconds: SIGNED_SECONDS }, session.supabase);
    if (!url) return notFound();
    return new Response(null, { status: 302, headers: { ...NO_STORE, location: url } });
  } catch (error) {
    console.error('Career file download failed', error);
    return notFound();
  }
}
